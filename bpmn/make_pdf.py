"""Builds the beginner-level report PDF: text pages (A4) + each diagram on its own large page (vector SVG),
so no diagram is ever cut or shrunk. Merges the parts with pdfunite."""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TMP = sys.argv[1] if len(sys.argv) > 1 else "/tmp/pdfparts"
OUT = os.path.join(os.path.dirname(HERE), "aeroflot_registration_bpmn_final.pdf")
CHROME = "/opt/pw-browsers/chromium-1194/chrome-linux/chrome"
os.makedirs(TMP, exist_ok=True)

CSS = """
*{box-sizing:border-box}
body{font-family:'DejaVu Sans',Arial,sans-serif;color:#1d1d1f;margin:0;font-size:13.5px;line-height:1.5}
h1{font-size:25px;margin:0 0 6px}
h2{font-size:19px;margin:22px 0 8px;padding-bottom:4px;border-bottom:2px solid #2d6cdf}
h3{font-size:15px;margin:16px 0 6px}
p{margin:6px 0}
ul,ol{margin:6px 0 6px 20px;padding:0}
li{margin:3px 0}
.sub{color:#666;font-size:12px}
table{border-collapse:collapse;width:100%;margin:8px 0;break-inside:avoid;page-break-inside:avoid}
th{background:#eaf1fd;text-align:left}
th,td{border:1px solid #b9c6dc;padding:7px 9px;vertical-align:top;font-size:13px}
td:first-child{font-weight:bold;white-space:nowrap}
.box{border:1px solid #b9c6dc;border-radius:6px;padding:8px 12px;background:#f7f9fd;margin:10px 0}
img.d{display:block;width:100%;border:1px solid #cfd8e6;margin:10px 0}
.cols{display:flex;gap:36px}.cols>div{flex:1}
.cap{font-size:12px;color:#555;margin:0 0 4px}
"""


def page(name, body, size, extra=""):
    html = f"<!doctype html><html lang='ru'><head><meta charset='utf-8'><style>{CSS}{extra}@page{{size:{size};margin:{'18mm 16mm' if 'mm' in size or size=='A4' else '30px 40px'}}}</style></head><body>{body}</body></html>"
    path = os.path.join(TMP, name + ".html")
    open(path, "w", encoding="utf-8").write(html)
    pdf = os.path.join(TMP, name + ".pdf")
    subprocess.run([CHROME, "--headless", "--no-sandbox", "--disable-gpu", "--no-pdf-header-footer",
                    f"--print-to-pdf={pdf}", "file://" + path], check=True, capture_output=True)
    return pdf


IMG = lambda n: "file://" + os.path.join(HERE, n)  # noqa: E731

